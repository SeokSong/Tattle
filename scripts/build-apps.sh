#!/bin/sh
# after editing Sources/Companies/Resources/apps.tsv: refreshes the apps entry in manifest.json
# (hash, row count, optional new version) and regenerates md/APPS-curated.md for owner review.
# it never downloads anything and never reads a capture or a report.
# usage: scripts/build-apps.sh [version]
set -eu
cd "$(dirname "$0")/.." || exit 1
res=Sources/Companies/Resources
tsv=$res/apps.tsv
manifest=$res/manifest.json
[ -f "$tsv" ] || { echo "no $tsv" >&2; exit 1; }

version=${1:-$(jq -r '.datasets[] | select(.file == "apps.tsv") | .version' "$manifest" 2>/dev/null | head -1)}
version=${version:-1}
sha=$(shasum -a 256 "$tsv" | cut -d' ' -f1)
rows=$(($(wc -l < "$tsv") - 1))
today=$(date -u +%Y-%m-%d)

jq --arg v "$version" --arg sha "$sha" --argjson rows "$rows" --arg d "$today" '
  .datasets = (.datasets | map(select(.file != "apps.tsv"))) + [{
    name: "Tattle app table", file: "apps.tsv", version: $v, commit: "",
    sourceURL: "", licence: "MIT (own data, public knowledge)", fetched: $d,
    sha256: $sha, sourceSHA256: $sha, rules: $rows }]' "$manifest" > "$manifest.new"
mv "$manifest.new" "$manifest"

out=md/APPS-curated.md
{
  echo "# App table"
  echo
  echo "Generated by \`scripts/build-apps.sh\` from \`$tsv\`. Do not edit by hand."
  echo
  echo "- Version $version, $rows rows, SHA-256 \`$sha\`"
  echo "- Rows are built from public knowledge of widely known apps and their publishers only; they are never chosen from anyone's captures or reports. The owner reviews them in the PR"
  echo "- A bundle id ending in a dot is a prefix: it covers every id that starts with it, unless a more specific row exists. A blank process name means it is not known with confidence"
  echo "- Process names are the executable names; the kernel's 16-character cut form is matched too"
  echo
  echo "## Counts per company"
  echo
  echo "| Company | Rows |"
  echo "|---|---|"
  awk -F'\t' 'NR>1 { n[$4]++ } END { for (c in n) print n[c] "\t" c }' "$tsv" | sort -t"$(printf '\t')" -k1,1nr -k2,2 |
    awk -F'\t' '{ print "| " $2 " | " $1 " |" }'
  echo "| Total | $rows |"
  echo
  echo "## Rows"
  echo
  echo "| Bundle id | App | Process name | Company | Rationale |"
  echo "|---|---|---|---|---|"
  awk -F'\t' 'NR>1 { print $4 "\t" $1 "\t" $2 "\t" $3 "\t" $5 }' "$tsv" | sort -t"$(printf '\t')" -k1,1 -k2,2 |
    awk -F'\t' '{ p = ($4 == "") ? "" : "`" $4 "`"; print "| `" $2 "` | " $3 " | " p " | " $1 " | " $5 " |" }'
} > "$out"
echo "updated $manifest ($rows rows, version $version) and $out"
