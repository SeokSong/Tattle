#!/bin/sh
# after editing Sources/Companies/Resources/curated.tsv: refreshes the curated entry in
# manifest.json (hash, row count, optional new version) and regenerates md/COMPANIES-curated.md
# for owner review. it never downloads anything.
# usage: scripts/build-curated.sh [version]
set -eu
cd "$(dirname "$0")/.." || exit 1
res=Sources/Companies/Resources
tsv=$res/curated.tsv
manifest=$res/manifest.json
[ -f "$tsv" ] || { echo "no $tsv" >&2; exit 1; }

version=${1:-$(jq -r '.datasets[] | select(.file == "curated.tsv") | .version' "$manifest" 2>/dev/null | head -1)}
version=${version:-1}
sha=$(shasum -a 256 "$tsv" | cut -d' ' -f1)
rows=$(($(wc -l < "$tsv") - 1))
today=$(date -u +%Y-%m-%d)

jq --arg v "$version" --arg sha "$sha" --argjson rows "$rows" --arg d "$today" '
  .datasets = (.datasets | map(select(.file != "curated.tsv"))) + [{
    name: "Tattle curated company list", file: "curated.tsv", version: $v, commit: "",
    sourceURL: "", licence: "MIT (own data, public knowledge)", fetched: $d,
    sha256: $sha, sourceSHA256: $sha, rules: $rows }]' "$manifest" > "$manifest.new"
mv "$manifest.new" "$manifest"

out=md/COMPANIES-curated.md
{
  echo "# Curated company list"
  echo
  echo "Generated by \`scripts/build-curated.sh\` from \`$tsv\`. Do not edit by hand."
  echo
  echo "- Version $version, $rows rows, SHA-256 \`$sha\`"
  echo "- Every row has \`source: curated\`. Rows are built from public knowledge only; the owner reviews them in the PR"
  echo "- Category labels: Advertising, Analytics, Social media, Content delivery, Cloud or app service, Apple system, Online service"
  echo
  echo "## Counts per category"
  echo
  echo "| Category | Rows |"
  echo "|---|---|"
  for c in advertising analytics social contentDelivery cloudService appleSystem onlineService; do
    echo "| $c | $(awk -F'\t' -v c="$c" 'NR>1 && $4==c' "$tsv" | wc -l | tr -d ' ') |"
  done
  echo "| Total | $rows |"
  for c in advertising analytics social contentDelivery cloudService appleSystem onlineService; do
    echo
    echo "## $c"
    echo
    echo "| Domain | Company | Parent | Rationale |"
    echo "|---|---|---|---|"
    awk -F'\t' -v c="$c" 'NR>1 && $4==c { print $1 "\t" $2 "\t" $3 "\t" $5 }' "$tsv" | sort |
      awk -F'\t' '{ print "| `" $1 "` | " $2 " | " $3 " | " $4 " |" }'
  done
} > "$out"
echo "updated $manifest ($rows rows, version $version) and $out"
